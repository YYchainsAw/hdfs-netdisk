package xyz.yychainsaw.backend.storage;

import java.io.FilterInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.HttpURLConnection;
import java.net.URI;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/** Internal WebHDFS client. HDFS is accessible only from the host loopback. */
@Component
public class HdfsStorage {
    private final int namenodePort;
    private final int datanodePort;

    public HdfsStorage(@Value("${netdisk.hdfs.namenode-port:9870}") int namenodePort,
                       @Value("${netdisk.hdfs.datanode-port:9864}") int datanodePort) {
        this.namenodePort = namenodePort;
        this.datanodePort = datanodePort;
    }

    private static void checkKey(String key) throws IOException {
        // Keys are generated by the server, never copied from user-supplied file names.
        if (key == null || key.length() > 240 || !key.matches("/netdisk/(temp|users)(/[A-Za-z0-9_-]+)*"))
            throw new IOException("Invalid storage key");
    }

    private HttpURLConnection request(String key, String query, String method) throws IOException {
        checkKey(key);
        URL url = URI.create("http://127.0.0.1:" + namenodePort + "/webhdfs/v1" + key + "?user.name=hdfs&" + query).toURL();
        return connection(url, method);
    }

    private HttpURLConnection connection(URL url, String method) throws IOException {
        HttpURLConnection c = (HttpURLConnection) url.openConnection();
        c.setInstanceFollowRedirects(false);
        c.setConnectTimeout(5000);
        c.setReadTimeout(60000);
        c.setRequestMethod(method);
        return c;
    }

    private URL redirect(HttpURLConnection c) throws IOException {
        String loc = c.getHeaderField("Location");
        try {
            URI uri = URI.create(loc);
            // Never send stored content or credentials to a redirected remote server.
            if (!"http".equalsIgnoreCase(uri.getScheme()) || !"127.0.0.1".equals(uri.getHost()) ||
                uri.getPort() != datanodePort || uri.getUserInfo() != null || uri.getFragment() != null ||
                uri.getPath() == null || !uri.getPath().equals(c.getURL().getPath()))
                throw new IOException("Untrusted HDFS redirect");
            return uri.toURL();
        } catch (IllegalArgumentException | NullPointerException ex) {
            throw new IOException("Invalid HDFS redirect", ex);
        }
    }

    private static IOException failure(String action, int code) {
        return new IOException("HDFS " + action + " failed (HTTP " + code + ")");
    }

    private static boolean responseBoolean(HttpURLConnection c) throws IOException {
        try (InputStream in = c.getInputStream()) {
            String result = new String(in.readNBytes(4096), StandardCharsets.UTF_8);
            if (result.matches("(?s).*\\\"boolean\\\"\\s*:\\s*true.*")) return true;
            if (result.matches("(?s).*\\\"boolean\\\"\\s*:\\s*false.*")) return false;
            throw new IOException("Invalid HDFS response");
        }
    }

    public void mkdirs(String key) throws IOException {
        HttpURLConnection c = request(key, "op=MKDIRS&permission=750", "PUT");
        try {
            int status = c.getResponseCode();
            if (status != 200) throw failure("mkdirs", status);
            if (!responseBoolean(c)) throw new IOException("HDFS mkdirs failed");
        } finally { c.disconnect(); }
    }

    public boolean exists(String key) throws IOException {
        HttpURLConnection c = request(key, "op=GETFILESTATUS", "GET");
        try {
            int status = c.getResponseCode();
            if (status == 404) return false;
            if (status != 200) throw failure("stat", status);
            return true;
        } finally { c.disconnect(); }
    }

    public long remaining() throws IOException {
        HttpURLConnection c=request("/netdisk/temp","op=GETSTATUS","GET");
        try {
            int status=c.getResponseCode();
            if(status!=200) throw failure("status",status);
            try(InputStream in=c.getInputStream()) {
                String json=new String(in.readNBytes(4096),StandardCharsets.UTF_8);
                Matcher m=Pattern.compile("\\\"remaining\\\"\\s*:\\s*(\\d+)").matcher(json);
                if(!m.find()) throw new IOException("Invalid HDFS filesystem status");
                try { return Long.parseLong(m.group(1)); }
                catch(NumberFormatException e) { throw new IOException("Invalid HDFS remaining capacity",e); }
            }
        } finally { c.disconnect(); }
    }

    public void write(String key, InputStream input, long size) throws IOException {
        if (size < 0) throw new IOException("Invalid content length");
        HttpURLConnection first = request(key, "op=CREATE&overwrite=false", "PUT");
        URL destination;
        try {
            int status = first.getResponseCode();
            if (status != 307) throw failure("create redirect", status);
            destination = redirect(first);
        } finally { first.disconnect(); }
        HttpURLConnection second = connection(destination, "PUT");
        second.setDoOutput(true);
        second.setFixedLengthStreamingMode(size);
        try {
            try (OutputStream out = second.getOutputStream()) {
                byte[] buffer = new byte[65536];
                long remaining = size;
                while (remaining > 0) {
                    int n = input.read(buffer, 0, (int) Math.min(buffer.length, remaining));
                    if (n < 0) throw new IOException("Content shorter than declared length");
                    if (n == 0) continue;
                    out.write(buffer, 0, n);
                    remaining -= n;
                }
                if (input.read() != -1) throw new IOException("Content longer than declared length");
            }
            int status = second.getResponseCode();
            if (status != 201) throw failure("write", status);
        } finally { second.disconnect(); }
    }

    public InputStream open(String key) throws IOException {
        HttpURLConnection first = request(key, "op=OPEN", "GET");
        URL destination;
        try {
            int status = first.getResponseCode();
            if (status != 307) throw failure("open redirect", status);
            destination = redirect(first);
        } finally { first.disconnect(); }
        HttpURLConnection second = connection(destination, "GET");
        try {
            int status = second.getResponseCode();
            if (status != 200) throw failure("open", status);
            return new FilterInputStream(second.getInputStream()) {
                @Override public void close() throws IOException {
                    try { super.close(); } finally { second.disconnect(); }
                }
            };
        } catch (IOException e) { second.disconnect(); throw e; }
    }

    public boolean rename(String from, String to) throws IOException {
        checkKey(to);
        HttpURLConnection c = request(from, "op=RENAME&destination=" + to, "PUT");
        try {
            int status = c.getResponseCode();
            if (status != 200) throw failure("rename", status);
            return responseBoolean(c);
        } finally { c.disconnect(); }
    }

    public void delete(String key) throws IOException {
        if ("/netdisk/temp".equals(key) || "/netdisk/users".equals(key)) throw new IOException("Cannot delete a storage root");
        HttpURLConnection c = request(key, "op=DELETE&recursive=false", "DELETE");
        try {
            int status = c.getResponseCode();
            if (status == 404) return;
            if (status != 200) throw failure("delete", status);
            if (!responseBoolean(c) && exists(key)) throw new IOException("HDFS delete returned false");
        } finally { c.disconnect(); }
    }
}

